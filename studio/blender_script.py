"""Turn a storyboard into a video_NN.py script for the Blender template.

The output follows the proven pattern of video_05..09: shots laid end to end with
a cursor, every say() returning its end frame, titles before the first camera call,
music and the 1.3 master gain at the end.  The script is plain Python so it can be
read, edited and re-run inside Blender like the hand-written ones.
"""

import json

from . import vocab
from .storyboard import line_map, normalize

HEADER = '''# Generated by Shorts Studio from storyboard "{title}".
# Edit freely; re-run the whole script after a change.
import bpy, os, aud
T = bpy.data.texts["stickman_tools.py"]
st = T.as_module()
S = bpy.context.scene
A = "//{audio_dir}/"
X = {X}; PH = {PH}
GAIN = 1.3
CUSTOM_POSES = {custom_poses}
PHONE_IN_HAND = {phone_in_hand}

st.clear_animation(); st.backdrop("{backdrop}")
for _k, _v in CUSTOM_POSES.items():
    st.POSES[_k] = _v
S.frame_end = 1800
S.render.filepath = "//{video_name}.mp4"

def on(name, f, x=None, z=None): st.place(name, f, x=x, z=z, scale=1.0, step=True)
def off(name, f): st.place(name, f, scale=0.0, step=True)
def popin(name, f, x=None, z=None):
    st.place(name, f, x=x, z=z, scale=0.6, step=True); st.place(name, f + 3, scale=1.1); st.place(name, f + 6, scale=1.0)
_B = [0.0, 0.0, 0.0]
def brow(f, tilt, lift=0.0, cock=0.0):
    st.brows(_B[0], _B[1], f - 1, _B[2]); st.brows(tilt, lift, f, cock); _B[:] = [tilt, lift, cock]
_LK = [0.0, 0.0]
def look(f, dx, dz):
    st.look(_LK[0], _LK[1], f - 1); st.look(dx, dz, f); _LK[:] = [dx, dz]
def L(path):
    s = aud.Sound.file(bpy.path.abspath(path)); return int(round(s.length / s.specs[0] * 30))
def speak(speaker, path, f, **kw):
    """Sticky lip-syncs; the phone talks with its face when it is on screen; others are off screen."""
    if not os.path.exists(bpy.path.abspath(path)):
        print("missing voice clip", path); return f + 45
    if speaker == "sticky":
        return st.say(path, f, **kw)
    if speaker == "phone" and PHONE_FACE[0]:
        return st.phone_say(path, f)
    st.voice(path, f, volume=0.9)
    return f + L(path)
PHONE_FACE = [False]
'''


def _f(v):
    return repr(round(float(v), 3))


def generate(sb, audio_dir="audio"):
    sb = normalize(sb)
    X = vocab.X_FURNITURE if sb["set"] in ("bed", "armchair") else vocab.X_PLAIN
    lines = line_map(sb)
    out = [HEADER.format(
        title=sb["title"].replace('"', "'"), audio_dir=audio_dir, X=X, PH=vocab.PHONE_X,
        custom_poses=json.dumps(vocab.CUSTOM_POSES), phone_in_hand=json.dumps(vocab.PHONE_IN_HAND),
        backdrop=sb["backdrop"], video_name=sb["video_name"].replace('"', "'"))]
    w = out.append

    # --- set and title (titles before any camera call) ---
    w('off("Set_Calendar", 1)')
    if sb["set"] == "bed":
        w('on("Set_Bed", 1); on("Set_Blanket", 1)')
        w('bl = bpy.data.objects["Set_Blanket"]; bl.location.y = 0.25; bl.keyframe_insert("location", frame=1)')
    elif sb["set"] == "armchair":
        w('on("Set_Sofa", 1)')
    title = sb["title"]
    if len(title) <= 23:
        w(f'st.title({title!r}, f_on=-8)')
    else:
        cut = title.rfind(" ", 0, 24)
        cut = cut if cut > 0 else 23
        w(f'st.title({title[:cut].strip()!r}, f_on=-8, y=3.17, size=0.36)')
        w(f'st.title({title[cut:].strip()!r}, f_on=-8, y=2.83, size=0.36)')

    uses_phone_face = any(lines.get(sh.get("line"), {}).get("speaker") == "phone"
                          and sh["camera"] in ("phone_screen", "phone_push") for sh in sb["shots"])
    if uses_phone_face:
        w('on("Phone_ScreenOff", 1)')

    first_pose = next((sh["pose"] for sh in sb["shots"] if sh.get("pose")), "phone")
    w(f'st.move_to(X, 0.0, 1); st.apply_pose({first_pose!r}, 1, face=False); st.mouth("neutral", 1)')
    if sb["holds_phone"]:
        x, z = vocab.PHONE_IN_HAND.get(first_pose, (0.62, 2.55))
        size = 0.6 if first_pose in vocab.PHONE_IN_HAND else 0
        w(f'st.hand_phone(1, {x}, {z}, size={size})')
    w("")
    w("c = 1                      # cursor: first frame of the current shot")
    w("starts = []; skip_blink = []; music_cuts = []")

    pose, eyes, lying, phone_shown = first_pose, "normal", False, first_pose in vocab.PHONE_IN_HAND

    for i, sh in enumerate(sb["shots"], 1):
        cam = vocab.CAMERAS[sh["camera"]]
        is_phone_cam = sh["camera"] in ("phone_screen", "phone_push")
        n = int(round(sh["seconds"] * vocab.FPS))
        w("")
        w(f"# --- shot {i}: {sh['camera']}, {sh['seconds']} s ---")
        w(f"c0 = c; e = c0 + {n}; starts.append(c0)")

        # camera
        x, z, s = cam["at"](X)
        w(f"st.cut(c0, {_f(x)}, {_f(z)}, {_f(s)})")

        # body: get up after a fall (he stays down for floor and phone shots), pose, phone in hand
        if lying and not is_phone_cam and sh["camera"] != "floor":
            w(f"st.flat(c0 - 1); st.move_to(X, 0.0, c0); st.apply_pose({(sh.get('pose') or 'stand')!r}, c0, face=False)")
            w("st.squint(c0, 1.0)")
            lying, eyes = False, "normal"
            pose = sh.get("pose") or "stand"
        elif sh.get("pose") and sh["pose"] != pose and not lying:
            w(f"st.snap({sh['pose']!r}, c0 + 1, face=False)")
            pose = sh["pose"]
        if sb["holds_phone"]:
            want = pose in vocab.PHONE_IN_HAND
            if want:
                px, pz = vocab.PHONE_IN_HAND[pose]
                w(f"st.hand_phone(c0 + 1, {px}, {pz}, size=0.6)")
            elif phone_shown:
                w("st.hand_phone(c0 + 1, 0.62, 2.55, size=0)")
            phone_shown = want

        # face
        if sh.get("eyes") and sh["eyes"] != eyes:
            if sh["eyes"] in ("squint", "shut"):
                w(f'st.eyes("normal", c0); st.squint(c0, {0.55 if sh["eyes"] == "squint" else 0.1})')
            else:
                if eyes in ("squint", "shut"):
                    w("st.squint(c0, 1.0)")
                w(f"st.eyes({sh['eyes']!r}, c0)")
            eyes = sh["eyes"]
        if sh.get("brows"):
            t, l, k = vocab.BROWS[sh["brows"]]
            w(f"brow(c0, {t}, {l}, {k})")
        if sh.get("look"):
            dx, dz = vocab.LOOKS[sh["look"]]
            w(f"look(c0, {dx}, {dz})")

        # spoken line (may stretch the shot)
        ln = lines.get(sh.get("line"))
        if ln:
            at = int(round(float(sh.get("line_at") or 0) * vocab.FPS))
            path = f'A + {ln.get("file", ln["id"] + ".mp3")!r}'
            kw = ""
            if ln["speaker"] == "sticky":
                end_mouth = sh.get("mouth") if sh.get("mouth") in ("smile", "grin", "sad", "neutral", "open") else "neutral"
                kw = f', end={end_mouth!r}'
                if sh.get("mouth") == "scream":
                    kw += ', closed="open", opened="scream"'
            if ln["speaker"] == "phone" and is_phone_cam:
                w("if not PHONE_FACE[0]:")
                w("    LIT = c0 + 2; st.phone_on(LIT)")
                w('    st.place("PFace", LIT, scale=1.0); st.place("PFace", LIT + 3, scale=1.62); st.place("PFace", LIT + 6, scale=1.5)')
                w("    st.phone_mood(LIT, lid=0.0, tilt=0.0, lift=0.06); st.phone_mood(LIT + 16)")
                w('    st.sfx("ding", LIT, 0.35); PHONE_FACE[0] = True')
            w(f"le = speak({ln['speaker']!r}, {path}, c0 + {at}{kw})  # {ln['text'][:60]!r}")
            w("e = max(e, le + 6)")
        elif sh.get("mouth"):
            w(f"st.mouth({sh['mouth']!r}, c0)")
        if eyes in ("wide", "money", "squint", "shut"):
            w("skip_blink.append([c0, e])")

        # camera move over the whole (final) shot length
        if "zoom_to" in cam:
            zx, zz, zs = cam["zoom_to"](X)
            a, b = cam.get("zoom_frames", (0, None))
            end = f"c0 + {b}" if b else "e - 1"
            w(f"st.zoom(c0 + {a}, {end}, x={_f(zx)}, z={_f(zz)}, scale={_f(zs)})")

        # action
        act = sh.get("action", "none")
        if act == "bounce":
            w("st.bounce(c0 + 3, height=0.3, length=12, sound=0.5)")
        elif act == "punch":
            w("st.punch(c0 + 1)")
        elif act == "spin":
            w('st.spin(c0 + 2, turns=2, length=16); st.sfx("whirl", c0 + 2, 0.7)')
        elif act == "flatten":
            w('st.flatten(c0 + 2, hold=14); st.sfx("splat", c0 + 2, 0.6)')
        elif act == "shiver":
            w("st.shiver(c0, e, 0.02)")
        elif act == "tears":
            w("st.tears(c0, e)")
        elif act == "walk":
            w("_m = (c0 + e) // 2; st.walk(c0, _m, X, X + 0.5, step=6); st.walk(_m, e, X + 0.5, X, step=5)")
        elif act == "hop":
            w("st.hop(c0 + 2, 0.25, 10)")
        elif act == "fall_flat":
            w('st.sfx("fall", c0, 0.3); st.flat(c0 + 6); st.squint(c0 + 6, 0.1)')
            w('st.sfx("splat", c0 + 6, 0.35); st.sfx("land", c0 + 6, 0.22)')
            w('st.fx("star", c0 + 6, 1.0, 1.32, 0.8); st.shake(c0 + 6, c0 + 12, 0.06)')
            lying, eyes = True, "shut"
        elif act == "coin_rain":
            w('st.sfx("chaching", c0 + 4, 0.6)')
            w("for _i in range(10):")
            w("    _f0 = c0 + _i * 2; _x = -1.6 + _i * 0.36")
            w('    st.place("Coin_%d" % (_i + 1), _f0, x=_x, z=6.1, scale=1.0, step=True)')
            w('    st.place("Coin_%d" % (_i + 1), _f0 + 22, z=-0.7)')
            w('    st.place("Coin_%d" % (_i + 1), _f0 + 23, scale=0.0, step=True)')
        if sh.get("shake") and act != "fall_flat":
            w("st.shake(c0 + 1, c0 + 9, 0.05)")

        # props and fx
        for p in sh["props"]:
            w(f"st.prop({p!r}, c0 + 2, e)")
        if sh.get("fx") == "lines":
            w("st.fx('lines', c0 + 1, X, 2.78, 1.0, length=e - c0 - 1)")
        elif sh.get("fx") == "star":
            w("st.fx('star', c0 + 2, X, 2.9, 0.8)")
        elif sh.get("fx") == "dust":
            w("st.fx('dust', c0 + 2, X, 0.1, 0.9)")

        # text
        cap = sh.get("caption")
        if cap and cap.get("text"):
            txt, col = cap["text"], cap.get("color", "black")
            if is_phone_cam:
                w(f"st.caption({txt!r}, c0 + 2, e, z=4.0, size=0.3, x=PH, max_width=2.6, color={col!r})")
            elif cap.get("pos") == "bottom":
                w("st.plate(c0 + 2, e, -2.7, lines=1)")
                w(f"st.caption({txt!r}, c0 + 2, e, z=-2.7, size=0.34, hud=True, color={col!r})")
            elif cap.get("pos") == "big":
                w(f"_t = st.caption({txt!r}, c0 + 2, e, z=1.5, size=0.62, hud=True, color={col!r}); st.pulse(_t, c0 + 6, e)")
            else:
                w(f"st.caption({txt!r}, c0 + 2, e, z=2.15, size=0.4, hud=True, color={col!r})")
        if is_phone_cam and sh.get("phone_text"):
            pt = [str(t) for t in sh["phone_text"]][:3]
            spots = [(2.85, 0.3, "black"), (2.05, 0.8, "black"), (1.3, 0.3, "red")]
            for (pz, psz, pcol), t in zip(spots, pt):
                w(f"st.caption({t!r}, c0 + 3, e, z={pz}, size={psz}, x=PH, max_width=2.6, color={pcol!r})")
            w('st.sfx("pop", c0 + 3, 0.5)')
        if sh["camera"] == "end_card" and sb.get("end_text"):
            et = list(sb["end_text"])[:2]
            w(f"st.caption({et[0]!r}, c0 + 3, e, z=0.45, size=0.36, hud=True, color='white')")
            if len(et) > 1:
                w(f"st.caption({et[1]!r}, c0 + 10, e, z=-0.05, size=0.48, hud=True, color='red')")

        # sound effects
        for s in sh["sfx"]:
            vol = s.get("volume", vocab.SFX.get(s["name"], 0.5))
            w(f"st.sfx({s['name']!r}, c0 + {int(round(float(s.get('at', 0)) * vocab.FPS))}, {vol})")
        if sh.get("music_stop"):
            w('music_cuts.append(c0); st.sfx("scratch", c0, 0.8)')
        w("c = e")

    # --- ending: length, music, mix, breathing ---
    music_file, music_vol = vocab.MUSIC.get(sb["music"], (None, 0))
    w("")
    w("END = c; S.frame_end = END")
    if music_file:
        w(f'm = st.music("//{music_file}", volume={music_vol}, fade=20, end=END + 1)')
        w(f"_keys = [(1, {music_vol})]")
        w("for _k, _c in enumerate(music_cuts):")
        w(f"    _keys += [(_c - 1, {music_vol}), (_c, 0.0)]")
        w("    _nxt = next((s for s in starts if s > _c), None)")
        w(f"    if _nxt: _keys += [(_nxt, {music_vol})]")
        w(f"_keys += [(END - 19, {round(music_vol * 0.8, 3)}), (END + 1, 0.0)]")
        w("for _fr, _v in sorted(set(_keys)):")
        w("    m.volume = _v * GAIN; m.keyframe_insert('volume', frame=_fr)")
    w("for s_ in st._strips():")
    w("    if s_.type == 'SOUND' and not s_.name.startswith('Music'): s_.volume *= GAIN")
    w("st.alive(1, END, blink_skip=[tuple(r) for r in skip_blink])")
    w('bpy.app.driver_namespace["studio_marks"] = {"starts": starts, "end": END}')
    w("S.frame_set(1)")
    return "\n".join(out) + "\n"
